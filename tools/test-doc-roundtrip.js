#!/usr/bin/env node
/* Round-trips a JS-built wire frame through the real doc.c parser.
 *
 * 'just test' otherwise only exercises appmessage.js's encoder in isolation:
 * nothing in CI ever confirms doc.c's next_token()/parse_rows() still agree
 * with it on field order or separators. Both sides carry hand-written
 * comments pointing at each other ("matching src/pkjs/appmessage.js" /
 * "Mirrors DocState in src/c/doc.h") but a comment cannot fail a build, so a
 * reordered field or a changed separator would only surface in the emulator
 * or on-device. This test turns that comment into an automated fitness
 * function by host-compiling doc.c (via tools/host-shim/pebble.h, a stub
 * that supplies only the libc bits doc.c actually needs -- it has no
 * graphics/SDK dependency) and piping appmessage.js's own buildPayload()
 * output into it through tools/doc_roundtrip_harness.c.
 *
 * Requires a host C compiler (cc). Run with: just test
 */

'use strict';

var path = require('path');
var fs = require('fs');
var child_process = require('child_process');
var Module = require('module');

/* message_keys is generated by the Pebble build from package.json; it does
 * not exist for a plain `node` run. Stubbed the same way tools/test-nav.js
 * and tools/test-session.js do, since appmessage.js requires it directly. */
var realResolve = Module._resolveFilename;
Module._resolveFilename = function (request) {
  if (request === 'message_keys') {
    return 'message_keys';
  }
  return realResolve.apply(this, arguments);
};
require.cache['message_keys'] = {
  id: 'message_keys', filename: 'message_keys', loaded: true,
  exports: { PAYLOAD: 9, CHUNK_IDX: 7, CHUNK_N: 8, STATE: 10, PROMPT_KIND: 11, LIVE: 12, ROOT: 13, SEQ: 6 }
};

var appmessage = require(path.join(__dirname, '..', 'src', 'pkjs', 'appmessage'));

var ROOT = path.join(__dirname, '..');
var BUILD_DIR = path.join(ROOT, 'build');
var HARNESS_BIN = path.join(BUILD_DIR, 'doc_roundtrip_harness');

var failures = 0;

function assert(label, condition) {
  console.log((condition ? 'ok   ' : 'FAIL ') + label);
  if (!condition) { failures++; }
}

function buildHarness() {
  fs.mkdirSync(BUILD_DIR, { recursive: true });
  var result = child_process.spawnSync('cc', [
    '-std=c99', '-Wall', '-Wextra', '-Werror',
    '-I', path.join(ROOT, 'tools', 'host-shim'),
    '-I', path.join(ROOT, 'src', 'c'),
    '-o', HARNESS_BIN,
    path.join(ROOT, 'tools', 'doc_roundtrip_harness.c'),
    path.join(ROOT, 'src', 'c', 'doc.c')
  ], { encoding: 'utf8' });

  if (result.status !== 0) {
    console.log(result.stdout || '');
    console.log(result.stderr || '');
    throw new Error('failed to host-compile doc.c (is a C compiler installed?)');
  }
}

/* Runs payload through the real parser and returns the parsed fields. */
function parse(payload) {
  var result = child_process.spawnSync(HARNESS_BIN, [], {
    input: payload,
    encoding: 'utf8'
  });
  if (result.status !== 0) {
    throw new Error('harness exited ' + result.status + ': ' + result.stderr);
  }

  var out = { rows: [] };
  var lines = result.stdout.split('\n');
  for (var i = 0; i < lines.length; i++) {
    if (!lines[i]) { continue; }
    var fields = lines[i].split('\t');
    if (fields[0] === 'ROW') {
      out.rows.push({
        kind: fields[2],
        label: fields[3],
        sublabel: fields[4] === '\x01' ? null : fields[4]
      });
    } else if (fields[0] !== 'ROWS') {
      /* ROWS is just the harness's row count, redundant with out.rows.length
       * once every ROW line has been collected; skipped here so it cannot
       * collide with the out.rows array itself. */
      out[fields[0].toLowerCase()] = fields[1] || '';
    }
  }
  return out;
}

function testBasicFrameRoundTrips() {
  var frame = {
    title: 'Pantry',
    message: 'All quiet',
    heading: 'Kettle',
    prompt: 'Full brew details go here',
    rows: [
      { label: 'Kettle', sublabel: 'cold', kind: 'p' },
      { label: 'Shelf', sublabel: null, kind: 'e' },
      { label: 'Brew', sublabel: 'starts a pot', kind: 'a' },
      { label: 'Next', sublabel: null, kind: 'l' },
      { label: 'Kitchen', sublabel: null, kind: 'b' }
    ]
  };

  var parsed = parse(appmessage.buildPayload(frame));

  assert('the title survives the wire', parsed.title === frame.title);
  assert('the message survives the wire', parsed.message === frame.message);
  assert('the heading survives the wire', parsed.heading === frame.heading);
  assert('the prompt survives the wire', parsed.prompt === frame.prompt);
  assert('every row arrives', parsed.rows.length === frame.rows.length);

  for (var i = 0; i < frame.rows.length; i++) {
    assert('row ' + i + ' label matches', parsed.rows[i].label === frame.rows[i].label);
    assert('row ' + i + ' kind matches', parsed.rows[i].kind === frame.rows[i].kind);
    assert('row ' + i + ' sublabel matches',
           parsed.rows[i].sublabel === frame.rows[i].sublabel);
  }
}

function testEmptyFrame() {
  var parsed = parse(appmessage.buildPayload({}));
  assert('a frame with no fields still parses', parsed.title === '');
  assert('a frame with no rows has none', parsed.rows.length === 0);
}

function testRowOverflowAppendsMoreRow() {
  var rows = [];
  for (var i = 0; i < 45; i++) {
    rows.push({ label: 'row' + i, kind: 'p' });
  }
  var parsed = parse(appmessage.buildPayload({ title: 'Overflow', rows: rows }));

  /* appmessage.js caps at MAX_ROWS (40) and appends a synthetic "(N more)"
   * row in the freed-up slot -- doc.c's own DOC_MAX_ROWS matches, so this
   * only proves anything if both constants still agree. */
  assert('overflow is capped, not silently truncated further',
         parsed.rows.length === 40);
  var last = parsed.rows[parsed.rows.length - 1];
  assert('the last row announces what was dropped', last.label === '(6 more)');
  assert('the "more" row is a plain property', last.kind === 'p');
}

function testControlCharactersCannotForgeASeparator() {
  /* A row label containing the raw wire separators would, if sanitise() ever
   * regressed, either merge into the next row or corrupt the kinds string.
   * doc.c has no escaping of its own -- sanitise() stripping every control
   * character before the wire is the *only* thing standing between "a
   * server-supplied string" and "a parser desync". */
  var frame = {
    title: 'Hostile',
    rows: [
      { label: 'a\x1ffield\nsep\ttrick', sublabel: 'x\x1fy', kind: 'p' },
      { label: 'second row', kind: 'e' }
    ]
  };
  var parsed = parse(appmessage.buildPayload(frame));

  assert('a hostile row cannot forge an extra row', parsed.rows.length === 2);
  assert('a hostile label loses its control characters, not its content',
         parsed.rows[0].label.indexOf('\x1f') === -1 &&
         parsed.rows[0].label.indexOf('\n') === -1);
  assert('the row after a hostile one still parses on its own',
         parsed.rows[1].label === 'second row');
}

function testMultiByteTextSurvivesByteOrientedParsing() {
  /* doc.c's next_token() walks the buffer with strchr(), one byte at a time
   * -- it never decodes UTF-8. truncate()'s ellipsis ("…") is
   * multi-byte, so this is also the one case in the suite that would catch
   * next_token() ever being changed to something that assumes single-byte
   * characters. */
  var longTitle = new Array(60).join('x');
  var parsed = parse(appmessage.buildPayload({ title: longTitle, rows: [] }));
  assert('a truncated multi-byte ellipsis round-trips intact',
         parsed.title === longTitle.slice(0, 47) + '…');
}

buildHarness();
testBasicFrameRoundTrips();
testEmptyFrame();
testRowOverflowAppendsMoreRow();
testControlCharactersCannotForgeASeparator();
testMultiByteTextSurvivesByteOrientedParsing();

if (failures) {
  console.log(failures + ' failure(s)');
  process.exit(1);
}
console.log('doc-roundtrip: all checks passed');
