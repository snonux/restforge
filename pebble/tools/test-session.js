function testUnreachableIsNotAnError() {
  setUp();
  session.listBackends();
  session.activate(0);

  /* status 0: the request never arrived anywhere. */
  FakeXHR.prototype.send = function () {
    requested.push(this.method + ' ' + this.url);
    this.status = 0;
    this.responseText = '';
    this.readyState = 4;
    this.onreadystatechange();
  };
  reset();
  session.refresh();

  var frame = lastFrame();
  assert('unreachable is its own state, not error', frame.state === 3);
  assert('unreachable says which host', /no answer from/.test(frame.prompt));
  FakeXHR.prototype.send = respondFromRoutes;
}

function testSwitchingBackendsResetsTheStack() {
  setUp();
  session.listBackends();
  session.activate(0);
  session.activate(indexOfRow(lastFrame(), 'shelves'));
  reset();

  session.listBackends();
  session.activate(1);
  reset();
  session.back();
  /* Not back into the first backend's documents: showing one server's state
   * under another server's name is the mistake this prevents. */
  assert('switching backends discards the old stack',
         lastFrame().kinds === 'bb');
}

