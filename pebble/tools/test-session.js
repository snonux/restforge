function testPicker() {
  setUp();
  session.listBackends();
  var frame = lastFrame();
  assert('the picker lists every backend', frame.rows.length === 2);
  assert('the picker rows are backend rows', frame.kinds === 'bb');
  assert('the picker asks for nothing over HTTP', requested.length === 0);

  storage = {};
  reset();
  session.listBackends();
  frame = lastFrame();
  /* Not an empty list: an empty menu is what a backend with nothing in it
   * would look like, and this is not that. */
  assert('no backends is needs-config, not an empty list', frame.state === 4);
  assert('no backends says what to do', frame.message === 'No backends');
}

