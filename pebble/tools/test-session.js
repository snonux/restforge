#!/usr/bin/env node
/* Checks session.js by driving it the way the watch does and decoding what
 * comes back off the wire.
 *
 * The assertions are made against the reassembled AppMessage payload rather
 * than against session.js's internals, so this covers the frame format,
 * chunking and row-index alignment as well as the navigation. Row indices are
 * the part most worth pinning down: the watch says "row 7 was pressed" and
 * nothing else, so if the rows it drew and the targets this module kept ever
 * disagree, a press quietly does the wrong thing rather than failing.
 *
 * session.js is a thin coordinator over nav.js (navigation, frame assembly,
 * idle refresh) and actions.js (Siren action field-filling, confirmation,
 * retry) -- see the module comment at the top of session.js. This file is
 * what exercises the three wired together, end to end, exactly as index.js
 * drives them; tools/test-nav.js and tools/test-actions.js exercise nav.js
 * and actions.js directly, in isolation from each other, including the cases
 * (e.g. the idle-refresh/pending-action hook) that only make sense to check
 * against one module at a time.
 *
 * Run with: just test
 */

