/* --- the bounded retry ---------------------------------------------------
 *
 * The one case where repeating a request is right: the user ticked a required
 * checkbox, and the server judged the same request twice on budgets that
 * changed in between.
 */

function testConfirmedActionRetriesOnce() {
  var root = openRoot();
  var attempts = 0;
  routes['POST ' + BASE + 'cool'] = { status: 409,
    body: { properties: { message: 'needs confirmation' } } };
  var saved = FakeXHR.prototype.send;
  FakeXHR.prototype.send = function (body) {
    if (this.method === 'POST') {
      attempts++;
      if (attempts === 2) {
        /* The retry is accepted, as the contract says it may be. */
        routes['POST ' + BASE + 'cool'] = { body: { properties: { state: 'done' } } };
      }
    }
    saved.call(this, body);
  };

  session.activate(indexOfRow(root, 'Let the kettle cool'));
  reset();
  session.answer(true);
  FakeXHR.prototype.send = saved;

  assert('a confirmed action is retried exactly once', attempts === 2);
  assert('both attempts carried the confirmation',
         sentBodies[0] === 'confirm=true' && sentBodies[1] === 'confirm=true');
  assert('the retry succeeding is what is reported',
         lastFrame().message === 'done');
}

function testUnconfirmedActionIsNotRetried() {
  var root = openRoot();
  routes['POST ' + BASE + 'brew'] = { status: 409,
    body: { properties: { message: 'a brew is already running' } } };
  session.activate(indexOfRow(root, 'Brew a pot of tea'));
  reset();
  session.answer(true);

  var posts = 0;
  for (var i = 0; i < requested.length; i++) {
    if (requested[i].indexOf('POST') === 0) { posts++; }
  }
  /* No required checkbox means nothing was confirmed, so there is nothing to
   * re-send -- and inventing one would be doing something nobody asked for. */
  assert('an action with nothing confirmed is never retried', posts === 1);
}

function testRetryIsNotRepeated() {
  var root = openRoot();
  routes['POST ' + BASE + 'cool'] = { status: 409,
    body: { properties: { message: 'still no' } } };
  session.activate(indexOfRow(root, 'Let the kettle cool'));
  reset();
  session.answer(true);

  var posts = 0;
  for (var i = 0; i < requested.length; i++) {
    if (requested[i].indexOf('POST') === 0) { posts++; }
  }
  assert('a retry that also conflicts is not retried again', posts === 2);
  assert('and the conflict is reported', lastFrame().message === 'Conflict');
}

/* --- idle refresh -------------------------------------------------------- */

function testIdleRefresh() {
  openRoot();
  tick(60000);
  assert('the visible document is re-read when idle',
         requested[requested.length - 1] === 'GET ' + BASE);

  /* A refresh nobody asked for must not take the screen away from someone
   * who is reading it. */
  var root = openRoot();
  session.activate(indexOfRow(root, 'kettle'));
  reset();
  tick(60000);
  assert('an open overlay suppresses it', requested.length === 0);

  /* Found in live use: the watch dismisses a reading overlay by itself, and
   * without a word from it the suppression latched on and the background
   * refresh never resumed. */
  var again = openRoot();
  session.activate(indexOfRow(again, 'kettle'));
  session.setSeq(99);
  session.dismissed();
  reset();
  tick(60000);
  assert('dismissing the overlay lets it resume',
         requested[requested.length - 1] === 'GET ' + BASE);

  /* And a quiet failure sets the banner rather than throwing an overlay over
   * whatever is on screen. */
  openRoot();
  routes = {};
  tick(60000);
  assert('a failed idle refresh does not open an overlay',
         lastFrame().overlay === 0);
  assert('but it does say so', lastFrame().message === 'Error');
}

/* Only the picker is the root, and only there does BACK leave the app. Getting
 * this wrong either traps the user inside RESTForge with no way out, or drops
 * them onto the watchface from the middle of a document. */
function testRootFlag() {
  setUp();
  session.listBackends();
  assert('the picker is the root', lastFrame().atRoot === 1);

  session.activate(0);
  assert('a document is not the root', lastFrame().atRoot === 0);

  session.activate(indexOfRow(lastFrame(), 'shelves'));
  assert('a deeper document is not the root', lastFrame().atRoot === 0);

  session.back();
  session.back();
  assert('back at the bottom returns to the root', lastFrame().atRoot === 1);
}

/* --- the quick menu ------------------------------------------------------
 *
 * Save the focused row, find it on the opening screen, press it. The property
 * being defended is that a shortcut skips the walking, not the deciding.
 */

