/* --- the runtime PebbleKit JS provides and node does not ----------------- */

/* message_keys is generated by the Pebble build from package.json. The values
 * do not matter here; only that appmessage.js can look them up. */
var MESSAGE_KEYS = {
  CMD: 1, IDX: 2, ANSWER: 3, ANSWER_TEXT: 4, INBOX: 5, SEQ: 6,
  CHUNK_IDX: 7, CHUNK_N: 8, PAYLOAD: 9, STATE: 10, PROMPT_KIND: 11, LIVE: 12,
  ROOT: 13
};

var realResolve = Module._resolveFilename;
Module._resolveFilename = function (request) {
  if (request === 'message_keys') {
    return 'message_keys';
  }
  return realResolve.apply(this, arguments);
};
require.cache['message_keys'] = {
  id: 'message_keys', filename: 'message_keys', loaded: true,
  exports: MESSAGE_KEYS
};

/* A clock the tests drive by hand. Polling is a state machine over time, and
 * the only way to test it deterministically is to own the time. */
var now = 1000000;
var timers = [];
var nextTimerId = 1;

global.setTimeout = function (fn, ms) {
  var id = nextTimerId++;
  timers.push({ id: id, at: now + (ms || 0), fn: fn });
  return id;
};
global.clearTimeout = function (id) {
  for (var i = 0; i < timers.length; i++) {
    if (timers[i].id === id) {
      timers.splice(i, 1);
      return;
    }
  }
};
Date.now = function () { return now; };

/* tick advances the clock and runs whatever came due, oldest first. */
function tick(ms) {
  var until = now + ms;
  for (;;) {
    var next = null;
    for (var i = 0; i < timers.length; i++) {
      if (timers[i].at <= until && (!next || timers[i].at < next.at)) {
        next = timers[i];
      }
    }
    if (!next) {
      break;
    }
    now = next.at;
    global.clearTimeout(next.id);
    next.fn();
  }
  now = until;
}

var storage = {};
global.localStorage = {
  getItem: function (key) {
    return Object.prototype.hasOwnProperty.call(storage, key) ? storage[key] : null;
  },
  setItem: function (key, value) { storage[key] = String(value); },
  removeItem: function (key) { delete storage[key]; }
};

