/* --- live mode -----------------------------------------------------------
 *
 * A job that outlives its request. The failure these guard against is a client
 * that reports "done" while the work is still running -- which is exactly what
 * happens if a poll landing on a machine that never saw the job is read as an
 * answer about it.
 */

var JOB = { class: ['kettle-job'], title: 'Kettle job',
            properties: { state: 'running', id: 7, step: 'heating the water',
                          staleAfterSeconds: 120 },
            links: [{ rel: ['self'], href: '/job' }] };

function jobBody(overrides) {
  var props = {};
  for (var key in JOB.properties) {
    if (Object.prototype.hasOwnProperty.call(JOB.properties, key)) {
      props[key] = JOB.properties[key];
    }
  }
  for (var over in overrides) {
    if (Object.prototype.hasOwnProperty.call(overrides, over)) {
      props[over] = overrides[over];
    }
  }
  return { class: ['kettle-job'], properties: props,
           links: [{ rel: ['self'], href: '/job' }] };
}

/* startBrew leaves a 202'd job being watched. */
function startBrew() {
  var root = openRoot();
  routes['POST ' + BASE + 'brew'] = { status: 202, body: jobBody({}) };
  routes[BASE + 'job'] = { body: jobBody({}) };
  session.activate(indexOfRow(root, 'Brew a pot of tea'));
  reset();
  session.answer(true);
}

function testLiveModeStartsOn202() {
  startBrew();
  assert('a 202 does not re-fetch and call it done',
         requested.length === 1 && requested[0].indexOf('POST') === 0);
  assert('the frame says it is live', lastFrame().atRoot === 0 &&
         sent[sent.length - 1][MESSAGE_KEYS.LIVE] === 1);
}

/* The poll target comes from matching the returned entity's class against the
 * origin document's link rels -- a hypermedia idiom, not a known path. */
function testPollTargetIsRelClassMatch() {
  startBrew();
  reset();
  tick(10000);
  assert('the job link is polled, not the origin',
         requested[0] === 'GET ' + BASE + 'job');
}

function testProgressIsReportedInTheServersWords() {
  startBrew();
  routes[BASE + 'job'] = { body: jobBody({ step: 'steeping' }) };
  reset();
  tick(10000);
  assert('the step is shown as the server worded it',
         lastFrame().message === 'steeping');
  assert('it is still live',
         sent[sent.length - 1][MESSAGE_KEYS.LIVE] === 1);
}

function testWatchingEndsAndRefetches() {
  startBrew();
  routes[BASE + 'job'] = { body: jobBody({ state: 'done', step: '' }) };
  reset();
  tick(10000);

  assert('the finished job is the last poll',
         requested[0] === 'GET ' + BASE + 'job');
  /* The job stopping is not the point -- the document it changed is. */
  assert('the origin document is re-fetched', requested[1] === 'GET ' + BASE);
  assert('the outcome is reported', lastFrame().message === 'done');
  assert('it is no longer live',
         sent[sent.length - 1][MESSAGE_KEYS.LIVE] === 0);
}

/* Load balancing means a poll can reach a machine that never saw this job.
 * "I do not have it" is not "it finished". */
function testPollAboutAnotherJobIsIgnored() {
  startBrew();
  routes[BASE + 'job'] = { body: jobBody({ id: 99, state: 'done' }) };
  reset();
  tick(10000);
  assert('an answer about another job does not end the watch',
         requested.length === 1);
  assert('and nothing claims it finished', lastFrame() === undefined);

  routes[BASE + 'job'] = { body: jobBody({ state: 'done' }) };
  tick(10000);
  assert('the right answer still ends it', lastFrame().message === 'done');
}

function testPollWithNoJobIsIgnored() {
  startBrew();
  routes[BASE + 'job'] = { body: jobBody({ state: 'none', id: 0 }) };
  reset();
  tick(10000);
  assert('a state of none does not end the watch', lastFrame() === undefined);
}

/* A failed poll is news about the network, not about the job. */
function testFailedPollKeepsWatching() {
  startBrew();
  delete routes[BASE + 'job'];
  routes[BASE + 'job'] = null;
  var saved = FakeXHR.prototype.send;
  FakeXHR.prototype.send = function () {
    requested.push(this.method + ' ' + this.url);
    this.status = 0;
    this.responseText = '';
    this.readyState = 4;
    this.onreadystatechange();
  };
  reset();
  tick(10000);
  assert('a failed poll does not end the watch', lastFrame() === undefined);
  FakeXHR.prototype.send = saved;
  routes[BASE + 'job'] = { body: jobBody({ state: 'done' }) };
  tick(10000);
  assert('watching resumes when the network does',
         lastFrame().message === 'done');
}

